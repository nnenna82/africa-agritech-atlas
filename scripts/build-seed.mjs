// Builds supabase/seed-1.sql and seed-2.sql from the JSON files in data/.
// Paste each file into the Supabase SQL Editor and click Run.
// Safe to re-run: existing rows are updated, new rows are added, nothing is deleted.
//
// Usage: node scripts/build-seed.mjs

import { readFileSync, writeFileSync } from "node:fs";

// Column lists must match supabase/schema.sql.
// Missing booleans become false and missing lists become empty, matching the schema defaults.
